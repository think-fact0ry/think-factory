// 폭 = 띄어쓰기 뺀 글자수 + 띄어쓰기수×0.3 (카드 폭에 맞춘 경험칙, 상한 8.3)
const width = (l) => [...l.replace(/ /g, '')].length + (l.split(' ').length - 1) * 0.3;
let bad = 0;
for (const [k, v] of Object.entries(FT)) {
  const lines = v.split('\n');
  if (lines.length !== 2) { console.error(`⚠ ${k} 줄수 ${lines.length}`); bad++; }
  for (const l of lines) if (width(l) > 8.3) { console.error(`⚠ ${k} 폭 ${width(l).toFixed(1)} "${l}"`); bad++; }
}
if (bad) { console.error(`규칙 위반 ${bad}건 — 중단`); process.exit(1); }

const data = JSON.parse(await readFile(POSTS, 'utf8'));
let n = 0, miss = [];
for (const p of data.posts) {
  if (p.kind !== 'activity') continue;
  if (FT[p.logNo]) { p.feedTitle = FT[p.logNo]; n++; }
  else miss.push(p.logNo);
}
await writeFile(POSTS, JSON.stringify(data, null, 1), 'utf8');
console.log(`2줄 제목 주입 ${n}건 / 매핑 ${Object.keys(FT).length}건`);
if (miss.length) console.warn(`매핑 없는 활동글 ${miss.length}건(3줄본 잔존 — 카드에서 활동명이 잘린다): ${miss.join(', ')}`);
